/**
 * Registers the form, field and success message blocks and renders them.
 *
 * Each form carries a random ID and a user editable name, so submissions can be
 * grouped and labelled in the admin. Fields are generic input types (text,
 * number, colour, file, dropdown, …) with their own label and properties
 * instead of a fixed set of quote-specific inputs.
 */
