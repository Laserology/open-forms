	/**
	 * The field types the editor can pick from, built from the shared registry.
	 *
	 * @return array
	 */
	private function field_types(): array {
		$types = array();

		foreach ( FieldHelpers::types() as $slug => $config ) {
			$types[] = array(
				'value'   => $slug,
				'label'   => $config['label'],
				'options' => ! empty( $config['options'] ),
			);
		}

		return $types;
	}

	/**
	 * Render the quote request form.
	 *
	 * @param array          $attributes Block attributes.
	 * @param string         $content    Rendered inner block content.
	 * @param \WP_Block|null $block      Block instance.
	 * @return string
	 */
	public function render( array $attributes, string $content = '', ?\WP_Block $block = null ): string {
		$source  = (int) get_the_ID();
		$form_id = $this->form_id( $attributes, $source );

		if ( '' === $form_id ) {
			return '';
		}

		$form_name = isset( $attributes['formName'] ) ? sanitize_text_field( (string) $attributes['formName'] ) : '';
		$form_name = '' !== $form_name ? $form_name : __( 'Quote form', 'open-forms' );
		$fields    = $block ? FormRegistry::fields_from_blocks( $block->inner_blocks ) : array();

		// Record the definition before submission: the handler validates the
		// posted values against it. Writes only when something changed.
		FormRegistry::remember( $form_id, $form_name, $fields, $source );

		$has_success = $block ? $this->has_block( $block->inner_blocks, 'openforms/quote-success' ) : false;
		$wrapper     = get_block_wrapper_attributes( array( 'class' => 'openforms-quote' ) );
		$notice      = $this->notice( $form_id, $has_success );
		$fields_html = $this->submit_button( (string) $content );

		// The picker is a themed button and the native control is hidden, so a
		// small script mirrors the chosen file names beside the button.
		wp_enqueue_script( 'openforms-quote-frontend', OPENFORMS_URL . 'assets/js/quote.js', array(), OPENFORMS_VERSION, true );

		// The form is multipart so file upload fields can post alongside the
		// text fields.
		$form  = '<form class="openforms-quote__form" method="post" enctype="multipart/form-data" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '">';
		$form .= '<input type="hidden" name="action" value="openforms_quote" />';
		$form .= '<input type="hidden" name="openforms_quote[form]" value="' . esc_attr( $form_id ) . '" />';
		$form .= $source ? '<input type="hidden" name="openforms_quote[source]" value="' . esc_attr( $source ) . '" />' : '';
		$form .= wp_nonce_field( 'openforms_quote_submit', 'openforms_quote_nonce', true, false );
		$form .= '<div class="openforms-quote__fields">' . $fields_html . '</div>';
		$form .= $this->status();
		$form .= '</form>';

		return sprintf( '<div %s>%s%s</div>', $wrapper, $notice, $form );
	}

	/**
	 * Render a single quote field.
	 *
	 * @param array          $attributes Block attributes.
	 * @param string         $content    Inner content (unused).
	 * @param \WP_Block|null $block      Block instance.
	 * @return string
	 */
	public function render_field( array $attributes, string $content = '', ?\WP_Block $block = null ): string {
		// Fields only render where a quote form provides their context, which
		// keeps them working inside layout containers without leaking an input
		// onto a page that has no form around it. The key is enough: blocks
		// saved before forms had IDs provide an empty value.
		if ( ! $block || ! array_key_exists( 'openforms/formId', $block->context ) ) {
			return '';
		}

		$field = FormRegistry::field( $this->raw_attributes( $attributes, $block ) );
		$types = FieldHelpers::types();
		$input = isset( $types[ $field['type'] ] ) ? $types[ $field['type'] ]['input'] : 'text';

		$support = \WP_Block_Supports::get_instance()->apply_block_supports();
		$class   = isset( $support['class'] ) ? ' ' . $support['class'] : '';
		$style   = isset( $support['style'] ) ? ' style="' . esc_attr( $support['style'] ) . '"' : '';

		// The border support is serialized manually onto the input itself (not
		// the label wrapper) so a border colour/size follows the field.
		$border      = $this->field_border( $attributes );
		$input_class = $border['class'] ? ' ' . $border['class'] : '';
		$input_style = $border['style'] ? ' style="' . esc_attr( $border['style'] ) . '"' : '';

		$key          = $field['key'];
		$id           = 'openforms-quote-' . $key;
		$name         = 'openforms_quote[' . $key . ']';
		$required     = $field['required'] ? ' required' : '';
		$placeholder  = '' !== $field['placeholder'] ? ' placeholder="' . esc_attr( $field['placeholder'] ) . '"' : '';
		$default      = isset( $field['default'] ) ? (string) $field['default'] : '';
		$mark         = $field['required'] ? ' <span class="required">*</span>' : '';
		$full         = $field['full'] ? ' openforms-quote__field--full' : '';

		if ( 'file' === $field['type'] ) {
			return $this->file_field( $field, $class, $style, $border );
		}

		$out  = '<p class="openforms-quote__field' . $full . $class . '"' . $style . '>';
		$out .= '<label class="openforms-quote__label" for="' . esc_attr( $id ) . '">' . esc_html( $field['label'] ) . $mark . '</label>';

		if ( 'textarea' === $input ) {
			$out .= '<textarea class="openforms-quote__textarea' . $input_class . '"' . $input_style . ' id="' . esc_attr( $id ) . '" name="' . esc_attr( $name ) . '"' . $placeholder . ' rows="4"' . $required . '>' . esc_textarea( $default ) . '</textarea>';
		} elseif ( 'select' === $input ) {
			$out .= '<select class="openforms-quote__select' . $input_class . '"' . $input_style . ' id="' . esc_attr( $id ) . '" name="' . esc_attr( $name ) . '"' . $required . '>';
			$out .= '<option value=""' . selected( '', $default, false ) . '>' . esc_html__( 'Select an option…', 'open-forms' ) . '</option>';

			foreach ( $field['options'] as $option ) {
				$out .= '<option value="' . esc_attr( $option ) . '"' . selected( $option, $default, false ) . '>' . esc_html( $option ) . '</option>';
			}

			$out .= '</select>';
		} else {
			$out .= '<input class="openforms-quote__input' . $input_class . '"' . $input_style . ' type="' . esc_attr( $input ) . '" id="' . esc_attr( $id ) . '" name="' . esc_attr( $name ) . '"' . $placeholder . ' value="' . esc_attr( $default ) . '"' . $required . ' />';
		}

		$out .= '</p>';

		return $out;
	}

	/**
	 * Render the virtual success message. The block is visible in the editor so
	 * its look and position can be tweaked, but the frontend only outputs it
	 * after this form is submitted successfully.
	 *
	 * @param array          $attributes Block attributes.
	 * @param string         $content    Inner content (unused).
	 * @param \WP_Block|null $block      Block instance.
	 * @return string
	 */
	public function render_success( array $attributes, string $content = '', ?\WP_Block $block = null ): string {
		if ( ! $block || ! array_key_exists( 'openforms/formId', $block->context ) ) {
			return '';
		}

		$form_id = sanitize_key( (string) $block->context['openforms/formId'] );

		// Older forms rendered their fields under a post based fallback ID.
		if ( '' === $form_id ) {
			$source  = (int) get_the_ID();
			$form_id = $source > 0 ? 'form-' . $source : '';
		}

		if ( '' === $form_id || 'success' !== $this->notice_type() ) {
			return '';
		}

		$notice_form = $this->notice_form();

		// The success message belongs to one specific form: a page can hold
		// several forms and only the submitted one should confirm.
		if ( $notice_form !== $form_id ) {
			return '';
		}

		$message = isset( $attributes['message'] ) ? wp_kses_post( (string) $attributes['message'] ) : '';

		if ( '' === trim( wp_strip_all_tags( $message ) ) ) {
			return '';
		}

		$wrapper = get_block_wrapper_attributes( array( 'class' => 'openforms-quote__notice openforms-quote__notice--success' ) );

		return sprintf( '<p %s>%s</p>', $wrapper, $message );
	}

	/**
	 * The block's stored attributes, without the defaults added while rendering.
	 * The default field type would otherwise hide the fact that an older field
	 * never stored one.
	 *
	 * @param array          $attributes Prepared attributes.
	 * @param \WP_Block|null $block      Block instance.
	 * @return array
	 */
	private function raw_attributes( array $attributes, ?\WP_Block $block ): array {
		if ( $block && isset( $block->parsed_block['attrs'] ) && is_array( $block->parsed_block['attrs'] ) ) {
			return $block->parsed_block['attrs'];
		}

		return $attributes;
	}

	/**
	 * Render the file upload field. The native control is hidden and the picker
	 * is a label carrying the core button classes, so the button picks up the
	 * site's button theme instead of hard-coded colours.
	 *
	 * @param array  $field  Field definition.
	 * @param string $class  Wrapper support classes.
	 * @param string $style  Wrapper support style attribute.
	 * @param array  $border Input border details.
	 * @return string
	 */
	private function file_field( array $field, string $class, string $style, array $border ): string {
		$button_class = $border['class'] ? ' ' . $border['class'] : '';
		$button_style = $border['style'] ? ' style="' . esc_attr( $border['style'] ) . '"' : '';
		$id           = 'openforms-quote-' . $field['key'];
		$mark         = $field['required'] ? ' <span class="required">*</span>' : '';

		$out  = '<p class="openforms-quote__field openforms-quote__field--full' . $class . '"' . $style . '>';
		$out .= '<span class="openforms-quote__label" id="' . esc_attr( $id ) . '-label">' . esc_html( $field['label'] ) . $mark . '</span>';
		$out .= '<span class="openforms-quote__file">';
		$out .= '<input type="file" class="openforms-quote__file-input" id="' . esc_attr( $id ) . '" name="openforms_quote_files[' . esc_attr( $field['key'] ) . '][]" accept="' . esc_attr( QuoteHandler::attachment_accept() ) . '" aria-labelledby="' . esc_attr( $id ) . '-label"' . ( $field['required'] ? ' required' : '' ) . ' multiple />';
		$out .= '<label class="openforms-quote__file-button wp-block-button__link wp-element-button' . $button_class . '"' . $button_style . ' for="' . esc_attr( $id ) . '">' . esc_html__( 'Choose files', 'open-forms' ) . '</label>';
		$out .= '<span class="openforms-quote__file-name" aria-live="polite"></span>';
		$out .= '</span>';
		$out .= '</p>';

		return $out;
	}

	/**
	 * The form ID for a block: the stored random ID, or a stable fallback for
	 * blocks saved before forms were identified.
	 *
	 * @param array $attributes Block attributes.
	 * @param int   $source     Current post ID.
	 * @return string
	 */
	private function form_id( array $attributes, int $source ): string {
		$id = isset( $attributes['formId'] ) ? sanitize_key( (string) $attributes['formId'] ) : '';

		if ( '' === $id && $source > 0 ) {
			$id = 'form-' . $source;
		}

		return $id;
	}

	/**
	 * The core button block saves an anchor, but the submit control inside the
	 * form has to be a real submit button, so swap the tag and drop the link
	 * attributes. Everything else, including the styling classes, is kept.
	 *
	 * @param string $content Rendered inner block content.
	 * @return string
	 */
	private function submit_button( string $content ): string {
		return preg_replace_callback(
			'/<a\s+([^>]*class="[^"]*wp-block-button__link[^"]*"[^>]*)>([\s\S]*?)<\/a>/',
			static function ( $matches ) {
				$attrs = preg_replace( '/\s(href|rel|target|role)="[^"]*"/', '', $matches[1] );

				return '<button type="submit" ' . $attrs . '>' . $matches[2] . '</button>';
			},
			$content
		);
	}

	/**
	 * Border classes and inline styles for a single field input, mirroring the
	 * block editor's border support. The border support serialization is
	 * skipped on the field wrapper (see the block registration) so the border
	 * lands on the input itself instead of the label wrapper.
	 *
	 * @param array $attributes Block attributes.
	 * @return array Array with 'class' and 'style' keys.
	 */
	private function field_border( array $attributes ): array {
		$border = isset( $attributes['style']['border'] ) ? $attributes['style']['border'] : array();

		if ( empty( $border ) && empty( $attributes['borderColor'] ) ) {
			return array( 'class' => '', 'style' => '' );
		}

		$border_styles = array();

		if ( isset( $border['radius'] ) && '' !== $border['radius'] ) {
			$border_styles['radius'] = is_numeric( $border['radius'] ) ? $border['radius'] . 'px' : $border['radius'];
		}

		if ( isset( $border['style'] ) && '' !== $border['style'] ) {
			$border_styles['style'] = $border['style'];
		}

		if ( isset( $border['width'] ) && '' !== $border['width'] ) {
			$border_styles['width'] = is_numeric( $border['width'] ) ? $border['width'] . 'px' : $border['width'];
		}

		// A palette colour is stored in the borderColor attribute and a custom
		// colour in style.border.color, exactly like core's border support.
		$preset_border_color = ! empty( $attributes['borderColor'] ) ? 'var:preset|color|' . $attributes['borderColor'] : null;
		$custom_border_color = isset( $border['color'] ) ? $border['color'] : null;

		if ( $preset_border_color || $custom_border_color ) {
			$border_styles['color'] = $preset_border_color ? $preset_border_color : $custom_border_color;
		}

		// Per-side border values.
		foreach ( array( 'top', 'right', 'bottom', 'left' ) as $side ) {
			if ( isset( $border[ $side ] ) && is_array( $border[ $side ] ) ) {
				$side_values = array();

				foreach ( array( 'width', 'color', 'style' ) as $prop ) {
					if ( isset( $border[ $side ][ $prop ] ) && '' !== $border[ $side ][ $prop ] ) {
						$value = $border[ $side ][ $prop ];

						if ( 'width' === $prop && is_numeric( $value ) ) {
							$value .= 'px';
						}

						$side_values[ $prop ] = $value;
					}
				}

				if ( $side_values ) {
					$border_styles[ $side ] = $side_values;
				}
			}
		}

		$styles = wp_style_engine_get_styles( array( 'border' => $border_styles ) );

		return array(
			'class' => isset( $styles['classnames'] ) ? $styles['classnames'] : '',
			'style' => isset( $styles['css'] ) ? $styles['css'] : '',
		);
	}

	/**
	 * Whether a block tree contains the given block.
	 *
	 * @param iterable $blocks Block instances.
	 * @param string   $name   Block name.
	 * @return bool
	 */
	private function has_block( iterable $blocks, string $name ): bool {
		foreach ( $blocks as $block ) {
			if ( $block instanceof \WP_Block && $name === $block->name ) {
				return true;
			}

			$inner = $block instanceof \WP_Block ? $block->inner_blocks : array();

			if ( ! empty( $inner ) && $this->has_block( $inner, $name ) ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * The submission status line. Empty and hidden until the form is submitted,
	 * then the script fills in the matching message so a large upload (or a slow
	 * server) does not look like a frozen page.
	 *
	 * @return string
	 */
	private function status(): string {
		return '<p class="openforms-quote__status" role="status" aria-live="polite" hidden data-sending="' . esc_attr__( 'Sending your request…', 'open-forms' ) . '" data-uploading="' . esc_attr__( 'Uploading your file, please wait…', 'open-forms' ) . '"></p>';
	}

	/**
	 * The error banners shown after a failed submission. A successful
	 * submission is shown by the success block instead, unless the form has no
	 * success block, in which case the notice falls back here.
	 *
	 * @param string $form_id     Current form ID.
	 * @param bool   $has_success Whether the form contains a success block.
	 * @return string
	 */
	private function notice( string $form_id, bool $has_success ): string {
		$type        = $this->notice_type();
		$notice_form = $this->notice_form();

		// Only the form that was submitted gets its notice on a page that has
		// more than one form.
		if ( '' !== $notice_form && $notice_form !== $form_id ) {
			return '';
		}

		if ( 'success' === $type ) {
			if ( ! $has_success && $notice_form === $form_id ) {
				return '<p class="openforms-quote__notice openforms-quote__notice--success">' . esc_html( self::success_message() ) . '</p>';
			}

			return '';
		}

		if ( 'file' === $type ) {
			return '<p class="openforms-quote__notice openforms-quote__notice--error">' . esc_html__( 'Sorry, the attached file could not be accepted. Please check its type and size and try again.', 'open-forms' ) . '</p>';
		}

		if ( 'throttle' === $type ) {
			return '<p class="openforms-quote__notice openforms-quote__notice--error">' . esc_html__( 'Sorry, you can only send one request every few minutes. Please try again shortly.', 'open-forms' ) . '</p>';
		}

		if ( 'error' === $type ) {
			return '<p class="openforms-quote__notice openforms-quote__notice--error">' . esc_html__( 'Sorry, your quote request could not be sent. Please try again.', 'open-forms' ) . '</p>';
		}

		return '';
	}

	/**
	 * The validated notice type from the query string, or empty.
	 *
	 * @return string
	 */
	private function notice_type(): string {
		if ( ! isset( $_GET['openforms_quote'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only status flag used to select a notice.
			return '';
		}

		$type = sanitize_key( wp_unslash( $_GET['openforms_quote'] ) ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only status flag used to select a notice.

		return in_array( $type, array( 'success', 'error', 'file', 'throttle' ), true ) ? $type : '';
	}

	/**
	 * The form the current notice belongs to, or empty for a generic notice.
	 *
	 * @return string
	 */
	private function notice_form(): string {
		if ( ! isset( $_GET['openforms_quote_form'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only status flag.
			return '';
		}

		return sanitize_key( wp_unslash( $_GET['openforms_quote_form'] ) ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only status flag.
	}

	/**
	 * Load the block stylesheet and editor script.
	 */
	public function editor_assets(): void {
		wp_enqueue_style( 'openforms-quote', OPENFORMS_URL . 'assets/css/quote.css', array(), OPENFORMS_VERSION );
		wp_enqueue_script( 'openforms-quote-editor' );
	}
}
